/**
 * Portable export: copy the compiled host into a folder that a technician can
 * carry to another Windows machine.
 *
 * The host is a plain .NET Framework executable, so once it is compiled it does
 * not need Node.js, the C# source, or this repository. `iebox export` writes the
 * exe plus a double-clickable launcher and a short note, which is the difference
 * between "install Node and read a README" and "copy this folder".
 */

import fs from 'node:fs';
import path from 'node:path';
import { OperationalError, VERSION } from './util.js';

export const EXPORT_EXE = 'iebox-host.exe';

/** Strip characters that cannot appear in a file name and keep it readable. */
function launcherName(url) {
  return url ? 'Open legacy site.cmd' : 'iebox.cmd';
}

/**
 * Write the double-clickable launcher.
 * @param {string} dir
 * @param {string | null} url
 * @returns {string} path
 */
export function writeLauncher(dir, url) {
  const target = url ? ` "${String(url).replace(/"/g, '')}"` : '';
  const body = [
    '@echo off',
    'rem Generated by iebox export - Node.js is not required on this machine.',
    `start "" "%~dp0${EXPORT_EXE}"${target}`,
    '',
  ].join('\r\n');

  const file = path.join(dir, launcherName(url));
  fs.writeFileSync(file, body, 'utf8');
  return file;
}

/**
 * Write the short operator note that ships with the folder.
 * @param {string} dir
 * @param {{ url?: string | null, arch?: string }} [meta]
 * @returns {string} path
 */
export function writeReadme(dir, meta = {}) {
  const lines = [
    'iebox - legacy Internet Explorer window',
    '=======================================',
    '',
    'Double-click the .cmd file in this folder.',
    meta.url ? `It opens: ${meta.url}` : 'It opens the saved home page.',
    '',
    'If the page needs an ActiveX control (camera and NVR panels usually do):',
    '',
    '  1. Internet Options -> Security -> Trusted sites -> Sites',
    '     add the device address, e.g. http://192.168.1.64',
    '  2. Still in Trusted sites: Custom level ->',
    '     "Initialize and script ActiveX controls not marked as safe" -> Prompt',
    '  3. Reload the page and accept the control prompt.',
    '',
    'If the plugin still does not appear, try an older emulation mode:',
    `  "${EXPORT_EXE}" --emulation ie8 http://192.168.1.64/`,
    '',
    `Architecture of this build: ${meta.arch || 'x86 (32-bit)'}.`,
    'Most vendor ActiveX controls are 32-bit only; rebuild with',
    '`iebox build --arch x64` for a 64-bit control.',
    '',
    'Security: this is the retired Trident/IE11 engine. It is unsandboxed and',
    'receives no security updates. Use it only for trusted legacy devices, and',
    'keep those devices on a network you control.',
    '',
    `Built with iebox ${VERSION}.`,
    '',
  ];
  const file = path.join(dir, 'README.txt');
  fs.writeFileSync(file, lines.join('\r\n'), 'utf8');
  return file;
}

/**
 * Copy the host and write the operator files.
 *
 * @param {{ dir: string, exePath: string, url?: string | null, arch?: string }} options
 * @returns {{ dir: string, exe: string, launcher: string, readme: string, url: string | null }}
 */
export function exportHost(options) {
  const { dir, exePath, url = null, arch } = options;
  if (!dir) throw new OperationalError('export needs a target directory.');
  if (!exePath || !fs.existsSync(exePath)) {
    throw new OperationalError(
      `The compiled host was not found at ${exePath || '(unknown)'}. Run \`iebox build\` first.`,
    );
  }

  fs.mkdirSync(dir, { recursive: true });
  const exe = path.join(dir, EXPORT_EXE);
  fs.copyFileSync(exePath, exe);

  const launcher = writeLauncher(dir, url);
  const readme = writeReadme(dir, { url, arch });

  return { dir, exe, launcher, readme, url: url || null };
}
